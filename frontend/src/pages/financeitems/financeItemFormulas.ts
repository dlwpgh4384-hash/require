/** 법인세(월할) 계산식. 마감된 달이 있으면 남은 달로 나눈다(시안 taxF). */
export function monthlyTaxFormula(closedCount: number, openCount: number) {
  return closedCount
    ? `(연간 예상액 − 마감된 ${closedCount}개월 반영액) ÷ 남은 ${openCount}개월`
    : "연간 예상액 ÷ 12";
}

/** 납부 일정 「구분」: 2026 MID → 「2026년 중간예납」, CNFM → 「2026년 확정 신고」. */
export function paymentKind(taxYear: number, paymentType: string) {
  return `${taxYear}년 ${paymentType === "MID" ? "중간예납" : "확정 신고"}`;
}

